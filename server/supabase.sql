-- SP Store · tabela de pedidos
-- Cole tudo no Supabase em: SQL Editor > New query > Run
create table if not exists public.pedidos (
  id bigint generated by default as identity (start with 1001) primary key,
  token uuid not null default gen_random_uuid(),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  user_id uuid references auth.users(id) on delete set null,
  email text not null,
  nome text,
  telefone text,
  endereco jsonb,
  itens jsonb not null,
  subtotal numeric(10,2) not null default 0,
  frete numeric(10,2) not null default 0,
  total numeric(10,2) not null default 0,
  status text not null default 'aguardando_pagamento',
  historico jsonb not null default '[]'::jsonb,
  emails jsonb not null default '{}'::jsonb,
  mp_pagamento text,
  mp_status text,
  forma_pagamento text,
  rastreio text,
  cpf text,
  envio jsonb
);
alter table public.pedidos add column if not exists cpf text;
alter table public.pedidos add column if not exists envio jsonb;

-- Configurações privadas da loja (dados do remetente para as etiquetas)
create table if not exists public.config (
  chave text primary key,
  valor jsonb not null
);
alter table public.config enable row level security;
revoke all on public.config from anon, authenticated;
create index if not exists pedidos_user_idx on public.pedidos (user_id);
create index if not exists pedidos_status_idx on public.pedidos (status);

-- Segurança: ninguém lê ou altera a tabela pelo navegador.
-- Só o servidor da loja (com a chave secreta) acessa os pedidos.
alter table public.pedidos enable row level security;
revoke all on public.pedidos from anon, authenticated;
